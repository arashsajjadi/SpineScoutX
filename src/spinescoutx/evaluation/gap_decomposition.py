"""2x2 oracle->auto gap decomposition (Phase 1). Diagnostic only; no retraining.

The oracle->auto severe-recall collapse conflates two changes: the in-plane crop
**centre** (GT coordinate vs localizer prediction) and the **slice** (GT-marked
instance vs geometric-mid instance). This module separates them with a controlled
2x2, holding the **series fixed to the GT sagittal-T2 series** so the only varying
factors are xy-source and slice-source:

  | cell | crop_xy_source | slice_source   | coordinate_source | isolates            |
  |------|----------------|----------------|-------------------|---------------------|
  | C1   | gt             | gt             | oracle            | upper bound         |
  | C2   | auto           | gt             | hybrid_debug      | in-plane error      |
  | C3   | gt             | geometric_mid  | hybrid_debug      | slice error         |
  | C4   | auto           | geometric_mid  | auto              | combined            |

``auto`` xy = the disc-level localizer's prediction run on the GT series'
geometric-mid slice (scaled to that series' pixel space). ``geometric_mid`` slice =
that series' middle DICOM instance. The two ``hybrid_debug`` cells use GT
information **only for diagnosis** and are never reported as a headline auto number.

All four cells are generated by ONE pipeline and are written atomically per node,
so every cell is scored on the identical set of (study, level) nodes — an
internally controlled decomposition. C1 should reproduce the established oracle
severe recall as a sanity check; C4 is the within-series analogue of the real auto
path (which additionally re-selects the series).

Research-only. Not diagnostic.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np

from ..constants import LEVELS
from ..data.crops import CropRecord, extract_25d, write_manifest
from ..data.localizer import _mid_instance, extract_peaks, peak_confidence
from ..utils.logging import get_logger
from ..utils.paths import ensure_dir

log = get_logger()

CELLS = ("c1_gtxy_gtslice", "c2_autoxy_gtslice", "c3_gtxy_midslice", "c4_autoxy_midslice")
CELL_PROVENANCE: dict[str, dict[str, str]] = {
    "c1_gtxy_gtslice": {
        "crop_xy_source": "gt",
        "slice_source": "gt",
        "coordinate_source": "oracle",
    },
    "c2_autoxy_gtslice": {
        "crop_xy_source": "auto",
        "slice_source": "gt",
        "coordinate_source": "hybrid_debug",
    },
    "c3_gtxy_midslice": {
        "crop_xy_source": "gt",
        "slice_source": "geometric_mid",
        "coordinate_source": "hybrid_debug",
    },
    "c4_autoxy_midslice": {
        "crop_xy_source": "auto",
        "slice_source": "geometric_mid",
        "coordinate_source": "auto",
    },
}


def _load_localizer(run_dir: str | Path, device):
    import torch

    from ..config import config_from_dict
    from ..models.disc_localizer import build_disc_localizer

    run_dir = Path(run_dir)
    cfg = config_from_dict(json.loads((run_dir / "config.json").read_text()))
    model = build_disc_localizer(cfg.model).to(device).eval()
    model.load_state_dict(torch.load(run_dir / "best.pt", map_location=device)["state_dict"])
    return model, int(cfg.data.crop_size)


def _localize_on_series(
    images_dir: Path, study: str, series_id: str, model, slice_size: int, device
) -> dict[str, Any] | None:
    """Run the localizer on the GT series' geometric-mid slice. Returns predicted
    5-level points (in that series' original pixel space), confidence, and mid inst."""
    import cv2
    import torch

    from ..data.dicom_io import normalize_intensity, read_dicom

    sdir = images_dir / study / series_id
    inst = _mid_instance(sdir)
    if inst is None:
        return None
    dpath = sdir / f"{inst}.dcm"
    try:
        img = normalize_intensity(read_dicom(dpath))
    except Exception as exc:  # noqa: BLE001 - logged, never faked
        log.warning("gap2x2 localize decode failed %s: %s", dpath, exc)
        return None
    h, w = img.shape
    resized = cv2.resize(img, (slice_size, slice_size), interpolation=cv2.INTER_AREA)
    with torch.no_grad():
        hm = model.heatmaps(torch.from_numpy(resized[None, None]).float().to(device))[0]
        hm = hm.cpu().numpy()
    peaks = extract_peaks(hm).astype(np.float64)
    conf = peak_confidence(hm)
    peaks[:, 0] *= w / slice_size
    peaks[:, 1] *= h / slice_size
    return {"points": peaks, "conf": conf, "mid_inst": int(inst), "h": int(h), "w": int(w)}


def _slice_dict(
    images_dir: Path, study: str, series_id: str, center: int, cache: dict
) -> dict[int, np.ndarray]:
    """Load {center-1, center, center+1} normalized slices (cached per (study,series,inst))."""
    from ..data.dicom_io import normalize_intensity, read_dicom

    out: dict[int, np.ndarray] = {}
    for i in (center - 1, center, center + 1):
        key = (study, series_id, i)
        if key in cache:
            if cache[key] is not None:
                out[i] = cache[key]
            continue
        p = images_dir / study / series_id / f"{i}.dcm"
        arr = None
        if p.exists():
            try:
                arr = normalize_intensity(read_dicom(p))
            except Exception:  # noqa: BLE001
                arr = None
        cache[key] = arr
        if arr is not None:
            out[i] = arr
    return out


def build_decomposition_crops(
    rsna_root: str | Path,
    localizer_run: str | Path,
    out_cache: str | Path,
    *,
    oracle_cache: str | Path = "data/cache/rsna",
    split: str = "val",
    crop_size: int = 224,
    limit_studies: int | None = None,
    device: str = "auto",
) -> dict[str, Any]:
    """Generate the four 2x2 cells on matched canal val nodes. Resume-safe.

    Nodes (and the GT series / instance / x,y) are taken from the **established
    cached oracle manifest** (``oracle_cache``) so C1 is *exactly* the project's
    oracle crop (no regeneration), and C2/C3/C4 vary xy/slice on the same series.
    This anchors the decomposition to the established oracle->auto gap rather than
    inventing a new oracle from a fresh coordinate join (which can pick a different
    sagittal-T2 series for a study and inflate the oracle).
    """
    from ..data.crops import read_manifest
    from ..data.rsna_index import RsnaPaths
    from ..training.optim import select_device

    rsna_root = Path(rsna_root)
    out = Path(out_cache)
    oracle_cache = Path(oracle_cache)
    images_dir = Path(RsnaPaths.from_root(rsna_root).train_images_dir)
    device_t = select_device(device)
    model, slice_size = _load_localizer(localizer_run, device_t)

    man = read_manifest(oracle_cache / "manifest.parquet")
    man = man[
        (man["condition"] == "spinal_canal_stenosis")
        & (man["split"] == split)
        & (man["severity_index"].isin([0, 1, 2]))
    ].copy()
    man["study_id"] = man["study_id"].astype(str)
    man["series_id"] = man["series_id"].astype(str)
    val_studies = sorted(man.study_id.unique())
    if limit_studies is not None:
        val_studies = val_studies[: int(limit_studies)]
        man = man[man.study_id.isin(set(val_studies))]

    auto_cells = ("c2_autoxy_gtslice", "c3_gtxy_midslice", "c4_autoxy_midslice")
    for cell in auto_cells:
        ensure_dir(out / cell / "crops")

    records: dict[str, list[CropRecord]] = {c: [] for c in CELLS}
    slice_cache: dict[tuple, Any] = {}
    localize_cache: dict[tuple, Any] = {}
    n_nodes = 0
    skipped_localize = 0
    skipped_slice = 0

    for study in val_studies:
        g = man[man.study_id == study]
        for series_id, gs in g.groupby("series_id"):
            series_id = str(series_id)
            lkey = (study, series_id)
            if lkey not in localize_cache:
                localize_cache[lkey] = _localize_on_series(
                    images_dir, study, series_id, model, slice_size, device_t
                )
            loc = localize_cache[lkey]
            if loc is None:
                skipped_localize += int(len(gs))
                continue
            mid_inst = loc["mid_inst"]
            for _, r in gs.iterrows():
                level = str(r.level)
                if level not in LEVELS:
                    continue
                li = LEVELS.index(level)
                gt_inst = int(r.instance_number)
                gt_x, gt_y = float(r.x), float(r.y)
                au_x, au_y = float(loc["points"][li, 0]), float(loc["points"][li, 1])
                sev = str(r.severity)
                sev_idx = int(r.severity_index)

                gt_slices = _slice_dict(images_dir, study, series_id, gt_inst, slice_cache)
                mid_slices = _slice_dict(images_dir, study, series_id, mid_inst, slice_cache)
                if gt_inst not in gt_slices or mid_inst not in mid_slices:
                    skipped_slice += 1
                    continue

                # C2/C3/C4 only (C1 reuses the established cached oracle crop).
                plan = {
                    "c2_autoxy_gtslice": (gt_inst, au_x, au_y, gt_slices),
                    "c3_gtxy_midslice": (mid_inst, gt_x, gt_y, mid_slices),
                    "c4_autoxy_midslice": (mid_inst, au_x, au_y, mid_slices),
                }
                built: dict[str, tuple] = {}
                ok = True
                for cell, (center, x, y, slices) in plan.items():
                    try:
                        arr, pad = extract_25d(slices, center, x, y, crop_size)
                    except Exception as exc:  # noqa: BLE001
                        log.warning("extract_25d failed %s %s %s: %s", study, level, cell, exc)
                        ok = False
                        break
                    built[cell] = (center, x, y, arr, pad)
                if not ok:
                    skipped_slice += 1
                    continue

                for cell, (center, x, y, arr, pad) in built.items():
                    rel = f"crops/{study}_{series_id}_{level}.npy"
                    fp = out / cell / rel
                    if not fp.exists():
                        np.save(fp, arr.astype(np.float32))
                    records[cell].append(
                        CropRecord(
                            study_id=study,
                            series_id=series_id,
                            instance_number=int(center),
                            condition="spinal_canal_stenosis",
                            level=level,
                            side=None,
                            severity=sev,
                            severity_index=sev_idx,
                            x=float(x),
                            y=float(y),
                            crop_path=rel,
                            dicom_path=str(images_dir / study / series_id / f"{center}.dcm"),
                            split=split,
                            sequence="sagittal_t2",
                            patient_id=study,
                            pad_note=pad,
                            coordinate_source=CELL_PROVENANCE[cell]["coordinate_source"],
                        )
                    )
                # C1: reference the established cached oracle crop verbatim.
                records["c1_gtxy_gtslice"].append(
                    CropRecord(
                        study_id=study,
                        series_id=series_id,
                        instance_number=gt_inst,
                        condition="spinal_canal_stenosis",
                        level=level,
                        side=None,
                        severity=sev,
                        severity_index=sev_idx,
                        x=gt_x,
                        y=gt_y,
                        crop_path=str(r.crop_path),
                        dicom_path=str(images_dir / study / series_id / f"{gt_inst}.dcm"),
                        split=split,
                        sequence="sagittal_t2",
                        patient_id=study,
                        pad_note=str(getattr(r, "pad_note", "")),
                        coordinate_source="oracle",
                    )
                )
                n_nodes += 1

    summary: dict[str, Any] = {
        "rsna_root": str(rsna_root),
        "localizer_run": str(localizer_run),
        "oracle_cache": str(oracle_cache),
        "out_cache": str(out),
        "split": split,
        "condition": "spinal_canal_stenosis",
        "crop_size": int(crop_size),
        "n_val_studies": len(val_studies),
        "n_matched_nodes": n_nodes,
        "skipped_localize_nodes": skipped_localize,
        "skipped_slice_nodes": skipped_slice,
        "cells": {},
    }
    cache_for = {c: str(out / c) for c in auto_cells}
    cache_for["c1_gtxy_gtslice"] = str(oracle_cache)
    for cell in CELLS:
        mp = write_manifest(records[cell], out / cell / "manifest.parquet")
        summary["cells"][cell] = {
            **CELL_PROVENANCE[cell],
            "n_crops": len(records[cell]),
            "manifest": str(mp),
            "cache_root": cache_for[cell],
        }
    return summary


