# evaluation: collect full 3-class probabilities for an image-only classifier
# --------------------------------------------------------------------------- #
def collect_probs(
    run_dir: str | Path, manifest_path: str | Path, cache_root: str | Path, device
) -> dict[str, tuple[int, np.ndarray]]:
    """Per-node ``"study|level" -> (y_true, probs3)`` for an E0-style image classifier."""
    import torch
    from torch.utils.data import DataLoader

    from ..config import config_from_dict
    from ..data.crops import read_manifest
    from ..data.datasets import RsnaCropDataset
    from ..training.train_classifier import _build_model, _is_guided

    run_dir = Path(run_dir)
    cfg = config_from_dict(json.loads((run_dir / "config.json").read_text()))
    if _is_guided(cfg):
        raise ValueError("collect_probs supports image-only (E0) models; got a guided model.")
    model = _build_model(cfg).to(device).eval()
    model.load_state_dict(torch.load(run_dir / "best.pt", map_location=device)["state_dict"])

    man = read_manifest(manifest_path)
    man = man[man["severity_index"].isin([0, 1, 2])].reset_index(drop=True)
    ds = RsnaCropDataset(
        man, cache_root, crop_size=cfg.data.crop_size, use_25d=cfg.data.use_25d, guided=False
    )
    keys = [f"{str(r.study_id)}|{str(r.level)}" for r in man.itertuples()]
    loader = DataLoader(ds, batch_size=64, shuffle=False, num_workers=4)
    out: dict[str, tuple[int, np.ndarray]] = {}
    idx = 0
    with torch.no_grad():
        for batch in loader:
            logits = model(
                batch["image"].to(device),
                level_idx=batch["level_idx"].to(device),
                condition_idx=batch["condition_idx"].to(device),
            )
            probs = torch.softmax(logits.float(), dim=1).cpu().numpy()
            tgt = batch["target"].numpy()
            for j in range(len(probs)):
                out[keys[idx]] = (int(tgt[j]), probs[j].astype(np.float64))
                idx += 1
    return out


def align_cells(
    cell_preds: dict[str, dict[str, tuple[int, np.ndarray]]],
) -> tuple[list[str], np.ndarray, dict[str, np.ndarray]]:
    """Intersect node keys across cells. Returns (study_ids, y_true, {cell: probs3})."""
    shared = set.intersection(*[set(p) for p in cell_preds.values()])
    keys = sorted(shared)
    any_cell = next(iter(cell_preds.values()))
    y = np.array([any_cell[k][0] for k in keys], dtype=int)
    studies = np.array([k.split("|")[0] for k in keys])
    probs = {c: np.stack([cell_preds[c][k][1] for k in keys]) for c in cell_preds}
    return list(studies), y, probs
